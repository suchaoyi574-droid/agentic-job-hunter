# TOOL 6
# Update Application State
# =====================================================

@mcp.tool()
def update_application_status(
    job_id: int,
    new_status: str,
    confirmed_by_user: bool,
) -> dict:
    """
    Record a verified application workflow status.

    IMPORTANT:
    This tool does NOT apply for a job.

    It only records an event that has already
    happened.

    Status changes require explicit human
    confirmation through confirmed_by_user=True.
    """

    if not confirmed_by_user:

        raise ToolError(
            "Human confirmation is required "
            "before changing job status."
        )


    new_status = (
        new_status
        .strip()
        .lower()
    )


    if new_status not in (
        ALLOWED_TRANSITIONS
    ):

        raise ToolError(
            f"Unknown status: "
            f"{new_status}"
        )


    init_database()

    conn = get_connection()

    try:

        row = conn.execute(
            """
            SELECT
                id,
                title,
                company,
                status
            FROM jobs
            WHERE id = ?
            """,
            (
                job_id,
            ),
        ).fetchone()


        if not row:

            raise ToolError(
                f"Job ID {job_id} "
                "does not exist."
            )


        current_status = (
            row["status"]
        )


        allowed = (
            ALLOWED_TRANSITIONS.get(
                current_status,
                set(),
            )
        )


        if new_status not in allowed:

            raise ToolError(
                f"Invalid state transition: "
                f"{current_status} "
                f"-> {new_status}. "
                f"Allowed transitions: "
                f"{sorted(allowed)}"
            )


        timestamp = datetime.now(
            timezone.utc
        ).isoformat()


        conn.execute(
            """
            UPDATE jobs

            SET
                status = ?,
                updated_at = ?

            WHERE id = ?
            """,
            (
                new_status,
                timestamp,
                job_id,
            ),
        )


        conn.commit()


        return {

            "job_id":
                job_id,

            "title":
                row["title"],

            "company":
                row["company"],

            "previous_status":
                current_status,

            "new_status":
                new_status,

            "updated_at":
                timestamp,
        }

    finally:

        conn.close()



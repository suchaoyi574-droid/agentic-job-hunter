import json
from datetime import datetime, timezone
from pathlib import Path

from mcp.server import MCPServer
from mcp.server.mcpserver.exceptions import ToolError

from database import get_connection, init_database


PROJECT_ROOT = Path(__file__).parent.resolve()
DATA_DIR = PROJECT_ROOT / "data"

RESUME_PATH = DATA_DIR / "resume.json"
TARGET_ROLES_PATH = DATA_DIR / "target_roles.json"
TOP_JOBS_PATH = DATA_DIR / "top_jobs.json"


# =====================================================
# MCP Server
# =====================================================

mcp = MCPServer(
    "Agentic Job Hunter"
)


# =====================================================
# State Machine
# =====================================================

ALLOWED_TRANSITIONS = {

    "discovered": {
        "matched",
    },

    "matched": {
        "reviewed",
    },

    "reviewed": {
        "applied",
    },

    "applied": {
        "interview",
        "rejected",
    },

    "interview": {
        "offer",
        "rejected",
    },

    "offer": set(),

    "rejected": set(),
}


# =====================================================
# Helpers
# =====================================================

def read_json(
    path: Path,
) -> dict:

    if not path.exists():

        raise ToolError(
            f"Required file does not exist: "
            f"{path.name}"
        )

    try:

        return json.loads(
            path.read_text(
                encoding="utf-8"
            )
        )

    except json.JSONDecodeError as exc:

        raise ToolError(
            f"Invalid JSON in "
            f"{path.name}: {exc}"
        )


def decode_json_list(
    value,
) -> list:

    if not value:
        return []

    try:
        return json.loads(value)

    except Exception:
        return []


def column_exists(
    conn,
    table: str,
    column: str,
) -> bool:

    rows = conn.execute(
        f"PRAGMA table_info({table})"
    ).fetchall()

    return any(
        row["name"] == column
        for row in rows
    )



# =====================================================
# TOOL 4
# List Jobs From SQLite
# =====================================================

@mcp.tool()
def list_jobs(
    status: str | None = None,
) -> list[dict]:
    """
    List jobs stored in the Agentic Job Hunter
    SQLite database.

    Optionally filter by status, for example:
    matched, reviewed, applied, interview,
    offer, or rejected.
    """

    init_database()

    conn = get_connection()

    try:

        has_decision = column_exists(
            conn,
            "jobs",
            "user_decision",
        )

        if has_decision:

            fields = """
                id,
                title,
                company,
                location,
                url,
                status,
                user_decision,
                created_at,
                updated_at
            """

        else:

            fields = """
                id,
                title,
                company,
                location,
                url,
                status,
                created_at,
                updated_at
            """


        if status:

            rows = conn.execute(
                f"""
                SELECT {fields}
                FROM jobs
                WHERE status = ?
                ORDER BY updated_at DESC
                """,
                (
                    status.strip().lower(),
                ),
            ).fetchall()

        else:

            rows = conn.execute(
                f"""
                SELECT {fields}
                FROM jobs
                ORDER BY updated_at DESC
                """
            ).fetchall()


        return [
            dict(row)
            for row in rows
        ]

    finally:

        conn.close()



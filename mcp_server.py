# TOOL 5
# Get One Job + Match Analysis
# =====================================================

@mcp.tool()
def get_job_details(
    job_id: int,
) -> dict:
    """
    Return a single job together with its matching
    analysis, missing skills, transferable strengths,
    recommendation, and current workflow status.
    """

    init_database()

    conn = get_connection()

    try:

        row = conn.execute(
            """
            SELECT

                j.id,
                j.title,
                j.company,
                j.location,
                j.description,
                j.experience,
                j.skills_json,
                j.url,
                j.status,
                j.created_at,
                j.updated_at,

                m.match_score,
                m.matched_skills_json,
                m.missing_skills_json,
                m.transferable_strengths_json,
                m.reasons_json,
                m.recommendation

            FROM jobs AS j

            LEFT JOIN matches AS m
                ON m.job_id = j.id

            WHERE j.id = ?
            """,
            (
                job_id,
            ),
        ).fetchone()


        if not row:

            raise ToolError(
                f"Job ID {job_id} "
                "does not exist."
            )


        result = dict(row)


        result["skills"] = decode_json_list(
            result.pop(
                "skills_json",
                None,
            )
        )


        result["matched_skills"] = (
            decode_json_list(
                result.pop(
                    "matched_skills_json",
                    None,
                )
            )
        )


        result["missing_skills"] = (
            decode_json_list(
                result.pop(
                    "missing_skills_json",
                    None,
                )
            )
        )


        result[
            "transferable_strengths"
        ] = decode_json_list(
            result.pop(
                "transferable_strengths_json",
                None,
            )
        )


        result["reasons"] = (
            decode_json_list(
                result.pop(
                    "reasons_json",
                    None,
                )
            )
        )


        if column_exists(
            conn,
            "jobs",
            "user_decision",
        ):

            review = conn.execute(
                """
                SELECT
                    user_decision,
                    reviewed_at
                FROM jobs
                WHERE id = ?
                """,
                (
                    job_id,
                ),
            ).fetchone()

            result[
                "user_decision"
            ] = review[
                "user_decision"
            ]

            result[
                "reviewed_at"
            ] = review[
                "reviewed_at"
            ]


        return result

    finally:

        conn.close()


